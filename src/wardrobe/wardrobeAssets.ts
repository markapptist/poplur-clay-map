export function wardrobeFallbackGlyph(type: WardrobeModuleType): string {
  return FALLBACK_GLYPHS[type]
}

export function wardrobeFallbackTone(assetId: string, type: WardrobeModuleType): string {
  const id = assetId.toLowerCase()
  if (id.includes('black')) return '#211b25'
  if (id.includes('white')) return '#f8eef4'
  if (id.includes('gold') || type === 'trophy' || type === 'jewelry') return '#d7a64a'
  if (type === 'plant') return '#5ca66f'
  if (type === 'mirror') return '#b9d8df'
  if (type === 'wardrobeFrame' || type === 'wardrobeDoor' || type === 'divider' || type === 'shelf' || type === 'cabinet') {
    return '#a85f3e'
  }
  return '#ff2d9a'
}


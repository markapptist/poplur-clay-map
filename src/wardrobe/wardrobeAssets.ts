export const wardrobeAssetRegistry: Record<string, WardrobeAssetDefinition> =
  Object.fromEntries(definitions.map(def => [def.assetId, def]))

export function getWardrobeAsset(id: string): WardrobeAssetDefinition | undefined {
  return wardrobeAssetRegistry[id]
}

/** Whether the definition has real module art. Empty sources deliberately use
    the renderer/library's code-native visual instead of a broken image probe. */
export function hasWardrobeAssetArt(def: WardrobeAssetDefinition): boolean {
  return def.source.trim().length > 0
}

export function assetSource(def: WardrobeAssetDefinition): string {
  if (!hasWardrobeAssetArt(def)) return ''
  // Access the one built-in value directly. Reading the whole import.meta.env
  // object makes Vite serialize every VITE_* setting into this public chunk.
  const configuredBase = import.meta.env.BASE_URL
  const base = typeof configuredBase === 'string' ? configuredBase : '/'
  return base.endsWith('/') ? `${base}${def.source}` : `${base}/${def.source}`
}

